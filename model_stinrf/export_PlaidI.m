%% export_PlaidI.m
%
% Writes the Type-I plaid figure. Runs in the workspace of run_PlaidI.m; that
% script calls it on its last line.
%
% Each icon carries the drift direction of both components and, in the
% pattern colour, the direction the plaid as a whole moves in. The curve
% takes that same pattern colour.

ex_icons = arrayfun(@(d) struct( ...
    'comp', [d + plaidI_offset, d - plaidI_offset], 'pattern', d), ...
    plaidI_dirs(:));

stinrf_export('PlaidI', "directions", struct( ...
    'xlabel', "Stimulus direction (deg)", 'line_role', "pattern", ...
    'x', plaidI_dirs(:).', 'y', pred(:).', ...
    'mae', mean(abs(err)), 'worst', max(abs(err)), ...
    'icons', ex_icons));

clear ex_icons

% A video of the plaid in every direction, rebuilt with the same call as the
% run loop. The two components add, so the luminance spans meanL*(1 +/- 2c)
% and that range is black to white; the mean stays mid grey.
for ex_i = 1:nP
    ex_m = make_plaidI(N, n_frames, f_cpx, sp, ...
                       plaidI_dirs(ex_i) + plaidI_offset, ...
                       plaidI_dirs(ex_i) - plaidI_offset, ...
                       phase, phase, contrast, meanL);
    stinrf_video(ex_m, framerate, ...
        sprintf('PlaidI_%d_%gdeg', ex_i, plaidI_dirs(ex_i)), ...
        'Clim', meanL*(1 + 2*contrast*[-1 1]));
end
clear ex_i ex_m
